#!/usr/bin/env python3
"""Portable exact proof receipts for prime-tuple bridge and path feasibility.

Certificate checks are finite modular arithmetic, NOT claims that tuples occur as primes.
"""
from __future__ import annotations
from hashlib import sha256
from math import prod
import json
from bridge_lab import offsets, admissible, primes_up_to, local_shift_residues, min_bridge_fast

DOMAIN=b'praetor.proof-frontier-bridge.v02\0'
def canon(x):return json.dumps(x,sort_keys=True,separators=(',',':'),ensure_ascii=True).encode()
def digest(x):return sha256(DOMAIN+canon(x)).hexdigest()
def translation(A,B,g):return A+tuple(A[-1]+g+b for b in B)

def bridge_receipt(a,b):
    A,B=offsets(a),offsets(b)
    if not admissible(A) or not admissible(B):raise ValueError('inputs are inadmissible')
    pp=primes_up_to(len(A)+len(B))
    constraints=[]
    for p in pp:
        ma=sorted(set(range(p))-{x%p for x in A})
        mb=sorted(set(range(p))-{x%p for x in B})
        good=sorted(local_shift_residues(A,B,p))
        constraints.append({'prime':p,'unused_left':ma,'unused_right':mb,'valid_bridge_residues':good})
    q=prod(pp)
    classes=prod(len(c['valid_bridge_residues']) for c in constraints)
    g=min_bridge_fast(A,B,q)
    assert g is not None
    statement={'type':'minimum_admissible_bridge','left':list(a),'right':list(b)}
    content={'statement':statement,'constraints':constraints,'crt_period':q,'valid_classes':classes,'minimum_bridge':g,'kind':'finite_modular_certificate','lean_checked':False,'historically_novel':False}
    return {'claim_id':digest(statement),'certificate_id':digest(content),'payload':content}

def verify_bridge_receipt(receipt):
    if set(receipt)!={'claim_id','certificate_id','payload'}:raise ValueError('wrong top-level fields')
    p=receipt['payload'];s=p['statement']
    if type(s)!=dict or set(s)!={'type','left','right'} or s['type']!='minimum_admissible_bridge':raise ValueError('bad statement')
    if len(s['left'])>7 or len(s['right'])>7 or not all(type(z)==int and z in (2,4,6,8,10) for z in s['left']+s['right']):raise ValueError('outside finite claim domain')
    expected=bridge_receipt(tuple(s['left']),tuple(s['right']))
    if receipt!=expected:raise ValueError('invalid or malleated mathematical certificate')
    return True

def join3(A,B,C,g,h):
    return translation(translation(A,B,g),C,h)

def local_path_classes(A,B,C,p):
    """Exact feasible (g,h) residues over (Z/p)^2, generated by direct union."""
    n=len(A)+len(B)+len(C)
    out=[]
    for g in range(p):
        for h in range(p):
            H=join3(A,B,C,g,h)
            if len({x%p for x in H})<p:out.append((g,h))
    return out

def path_receipt(a,b,c):
    A,B,C=(offsets(w) for w in (a,b,c))
    if not all(admissible(x) for x in (A,B,C)):raise ValueError('inadmissible input')
    pp=primes_up_to(len(A)+len(B)+len(C))
    q=prod(pp)
    local=[{'prime':p,'valid_pair_residues':local_path_classes(A,B,C,p)} for p in pp]
    classes=prod(len(x['valid_pair_residues']) for x in local)
    assert classes>0
    # shortest first join, then second, with full global validation
    g0=min_bridge_fast(A,B)
    greedy_h=next(h for h in range(2,q+1,2) if admissible(join3(A,B,C,g0,h)))
    greedy=(g0,greedy_h)
    best=None
    for total in range(4,sum(greedy)+1,2):
        for g in range(2,total,2):
            h=total-g
            if admissible(join3(A,B,C,g,h)):
                best=(g,h)
                break
        if best:break
    assert best
    statement={'type':'minimum_three_way_bridge_cost','motifs':[list(a),list(b),list(c)],'cost':'g+h'}
    content={'statement':statement,'prime_moduli':list(pp),'local_class_sizes':{str(x['prime']):len(x['valid_pair_residues']) for x in local},'crt_period':q,'valid_pair_classes':classes,'greedy_bridges':list(greedy),'optimal_bridges':list(best),'total_greedy':sum(greedy),'total_optimal':sum(best),'scope':'admissibility only, no prime occurrences or Lean proof','lean_checked':False}
    return {'claim_id':digest(statement),'certificate_id':digest(content),'payload':content}

def verify_path_receipt(receipt):
    if set(receipt)!={'claim_id','certificate_id','payload'}:raise ValueError('bad receipt')
    p=receipt['payload'];s=p['statement']
    if s.get('type')!='minimum_three_way_bridge_cost':raise ValueError('bad statement type')
    motifs=s.get('motifs')
    if type(motifs)!=list or len(motifs)!=3 or any(type(x)!=list or len(x)!=2 for x in motifs):raise ValueError('unsupported family')
    if any(type(z)!=int or z not in (2,4,6,8,10) for x in motifs for z in x):raise ValueError('bad motifs')
    expected=path_receipt(*(tuple(w) for w in motifs))
    if receipt!=expected:raise ValueError('altered receipt')
    return True